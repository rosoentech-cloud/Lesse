"""Builds the text the chat assistant uses. Run by tools/build.py.

Two files come out of the built pages and the blog list:
- ai-worker/site-knowledge.js: the full text the Cloudflare worker sends to Claude.
- assets/js/site-data.js: short searchable pieces the chat box uses when no AI endpoint is set.

Both come from the visible text of the built pages, so the assistant can only say what the site says.
"""
import json
import os
import re
from html.parser import HTMLParser

from site_lib import BASE, EMAIL, PHONE_DISPLAY, SITE, WHATSAPP, page_url, write

PAGES = [
    'index.html',
    'services.html',
    'research-support.html',
    'editing-proofreading.html',
    'citations-formatting.html',
    'proposals-grants.html',
    'business-copy.html',
    'resumes-cvs.html',
    'payments.html',
    'policies.html',
    'contact.html',
    'post-project.html',
]

CHUNK_CHARS = 450
SENTENCE_END = ('.', '!', '?', ':', ')', '"', "'")
SKIP_TAGS = {'script', 'style', 'form', 'button'}
BLOCK_TAGS = {'h1', 'h2', 'h3', 'h4', 'p', 'li', 'summary', 'dt', 'dd', 'br',
              'div', 'span', 'section', 'article', 'tr'}


class VisibleText(HTMLParser):
    """Collects the readable text inside <main>, one entry per block."""

    def __init__(self):
        super().__init__()
        self.in_main = False
        self.skip = 0
        self.parts = []

    def handle_starttag(self, tag, attrs):
        if tag == 'main':
            self.in_main = True
        if tag in SKIP_TAGS:
            self.skip += 1
        if tag in BLOCK_TAGS:
            self.parts.append('\n')

    def handle_endtag(self, tag):
        if tag == 'main':
            self.in_main = False
        if tag in SKIP_TAGS and self.skip:
            self.skip -= 1
        if tag in BLOCK_TAGS:
            self.parts.append('\n')

    def handle_data(self, data):
        if self.in_main and not self.skip:
            self.parts.append(data)

    def lines(self):
        cleaned = (re.sub(r'\s+', ' ', line).strip() for line in ''.join(self.parts).split('\n'))
        return [line for line in cleaned if line]


def page_info(rel):
    with open(os.path.join(SITE, rel), encoding='utf-8') as f:
        html = f.read()
    title = re.search(r'<title>(.*?)</title>', html, re.S).group(1).strip()
    parser = VisibleText()
    parser.feed(html)
    return title, parser.lines()


def chunk_lines(title, url, lines):
    """Splits text into pieces of about CHUNK_CHARS characters, breaking only between lines."""
    pieces, current = [], ''
    for line in lines:
        if current and len(current) + len(line) + 1 > CHUNK_CHARS:
            pieces.append(current)
            current = ''
        if not line.endswith(SENTENCE_END):
            line += '.'
        current = (current + ' ' + line).strip()
    if current:
        pieces.append(current)
    return [{'title': title, 'url': url, 'text': piece} for piece in pieces]


def write_knowledge(posts):
    contact = [
        f'Phone: {PHONE_DISPLAY}',
        f'WhatsApp: {WHATSAPP}',
        f'Email: {EMAIL}',
        'The brief form and the contact form both send to the Lesse inbox. '
        'Replies go to the email address the visitor enters.',
    ]
    worker_parts = [
        f'Site: Lesse ({BASE}). Everything below is taken from the website itself.',
        '## Contact details\n' + '\n'.join(contact),
    ]
    chunks = chunk_lines('Contact details', page_url('contact.html'), contact)

    for rel in PAGES:
        title, lines = page_info(rel)
        url = page_url(rel)
        worker_parts.append(f'## {title}\nURL: {url}\n' + '\n'.join(lines))
        chunks += chunk_lines(title, url, lines)

    listing = sorted(posts.values(), key=lambda p: p['date'], reverse=True)
    blog_lines = []
    for p in listing:
        url = page_url('blog/' + p['slug'] + '.html')
        blog_lines.append(f"- {p['title']} ({p['category']}, {p['date']}): {p['description']} URL: {url}")
        chunks.append({'title': p['title'], 'url': url, 'text': f"{p['category']}. {p['description']}"})
    worker_parts.append('## Blog articles\n' + '\n'.join(blog_lines))

    body = '\n\n'.join(worker_parts)
    header = '// Generated by tools/build.py from the website. Do not edit by hand.\n'
    write('ai-worker/site-knowledge.js',
          header + 'export const SITE_KNOWLEDGE = ' + json.dumps(body, ensure_ascii=False) + ';\n')
    write('assets/js/site-data.js',
          header + '// Short pieces of the site text that the chat box searches when no AI endpoint is set.\n'
          'window.SITE_CHUNKS = ' + json.dumps(chunks, ensure_ascii=False) + ';\n')
    print(f'site knowledge written: {len(body)} characters; {len(chunks)} search pieces')
